#!/usr/bin/env bash
# Build a throwaway git repo with a real merge conflict for testing the merge-develop skill.
#
#   setup_fixture.sh <scenario> <dest_dir>
#
# Produces <dest_dir>/origin.git (bare remote) + <dest_dir>/repo (working clone),
# left checked out on branch `feature`, with origin/develop holding conflicting work.
#
# Scenarios:
#   code-intent-merge   both branches add a different field to the same object (must keep BOTH)
#   generated-file-regen  both edit a source + its generated output (must regenerate, not hand-merge)
#   dirty-tree-stash    conflict in a tracked file PLUS uncommitted + untracked work (must stash/reapply)
set -euo pipefail

SCENARIO="${1:?usage: setup_fixture.sh <scenario> <dest_dir>}"
DEST="${2:?usage: setup_fixture.sh <scenario> <dest_dir>}"

rm -rf "$DEST"
mkdir -p "$DEST"
DEST="$(cd "$DEST" && pwd)"

GIT="git -c user.name=Fixture -c user.email=fixture@test.local -c commit.gpgsign=false -c init.defaultBranch=main -c advice.detachedHead=false"

$GIT init --bare "$DEST/origin.git" >/dev/null
$GIT init "$DEST/repo" >/dev/null
cd "$DEST/repo"
$GIT remote add origin "$DEST/origin.git"

commit() { $GIT add -A; $GIT commit -q -m "$1"; }

case "$SCENARIO" in

  code-intent-merge)
    mkdir -p src
    cat > src/settings.ts <<'EOF'
export const settings = {
  name: "app",
};
EOF
    cat > package.json <<'EOF'
{
  "name": "fixture-a",
  "scripts": { "test": "node test.js" }
}
EOF
    cat > test.js <<'EOF'
const fs = require("fs");
const src = fs.readFileSync("src/settings.ts", "utf8");
if (/[<>=]{7}/.test(src)) { console.error("FAIL: conflict markers present"); process.exit(1); }
const missing = ["name", "timeout", "retries"].filter((k) => !src.includes(k));
if (missing.length) { console.error("FAIL: missing keys: " + missing.join(", ")); process.exit(1); }
console.log("ok: name, timeout, retries all present");
EOF
    commit "base: settings + test"
    $GIT push -q origin main

    $GIT checkout -q -b develop
    cat > src/settings.ts <<'EOF'
export const settings = {
  name: "app",
  timeout: 5000,
};
EOF
    commit "develop: add timeout"
    $GIT push -q origin develop

    $GIT checkout -q main
    $GIT checkout -q -b feature
    cat > src/settings.ts <<'EOF'
export const settings = {
  name: "app",
  retries: 3,
};
EOF
    commit "feature: add retries"
    ;;

  generated-file-regen)
    mkdir -p src data scripts
    cat > data/chains.json <<'EOF'
[
  { "id": 1, "name": "ethereum" }
]
EOF
    cat > scripts/generate.js <<'EOF'
// Regenerates data/chains.generated.json from data/chains.json. Do not hand-edit the output.
const fs = require("fs");
const chains = JSON.parse(fs.readFileSync("data/chains.json", "utf8"));
const out = {
  _note: "generated by scripts/generate.js - do not edit",
  count: chains.length,
  names: chains.map((c) => c.name).sort(),
};
fs.writeFileSync("data/chains.generated.json", JSON.stringify(out, null, 2) + "\n");
console.log("generated " + out.count + " chains");
EOF
    cat > data/chains.generated.json <<'EOF'
{
  "_note": "generated by scripts/generate.js - do not edit",
  "count": 1,
  "names": [
    "ethereum"
  ]
}
EOF
    cat > data/README.md <<'EOF'
`data/chains.generated.json` is generated from `data/chains.json` by
`npm run generate` (scripts/generate.js). Do not edit the generated file by hand.
EOF
    cat > scripts/check.js <<'EOF'
const fs = require("fs");
const cp = require("child_process");
const raw = fs.readFileSync("data/chains.json", "utf8");
if (/[<>=]{7}/.test(raw)) { console.error("FAIL: markers in chains.json"); process.exit(1); }
const names = JSON.parse(raw).map((c) => c.name).sort();
const missing = ["ethereum", "base", "arbitrum"].filter((n) => !names.includes(n));
if (missing.length) { console.error("FAIL: missing chains: " + missing.join(", ")); process.exit(1); }
const committed = fs.readFileSync("data/chains.generated.json", "utf8").trim();
cp.execSync("node scripts/generate.js");
const fresh = fs.readFileSync("data/chains.generated.json", "utf8").trim();
if (committed !== fresh) { console.error("FAIL: generated file does not match a fresh regenerate"); process.exit(1); }
console.log("ok: all chains present and generated file is consistent");
EOF
    cat > package.json <<'EOF'
{
  "name": "fixture-b",
  "scripts": {
    "generate": "node scripts/generate.js",
    "test": "node scripts/check.js"
  }
}
EOF
    commit "base: chains + generator"
    $GIT push -q origin main

    $GIT checkout -q -b develop
    cat > data/chains.json <<'EOF'
[
  { "id": 1, "name": "ethereum" },
  { "id": 2, "name": "base" }
]
EOF
    cat > data/chains.generated.json <<'EOF'
{
  "_note": "generated by scripts/generate.js - do not edit",
  "count": 2,
  "names": [
    "base",
    "ethereum"
  ]
}
EOF
    commit "develop: add base chain"
    $GIT push -q origin develop

    $GIT checkout -q main
    $GIT checkout -q -b feature
    cat > data/chains.json <<'EOF'
[
  { "id": 1, "name": "ethereum" },
  { "id": 3, "name": "arbitrum" }
]
EOF
    cat > data/chains.generated.json <<'EOF'
{
  "_note": "generated by scripts/generate.js - do not edit",
  "count": 2,
  "names": [
    "arbitrum",
    "ethereum"
  ]
}
EOF
    commit "feature: add arbitrum chain"
    ;;

  dirty-tree-stash)
    mkdir -p src
    cat > src/routes.ts <<'EOF'
export const routes = [
  "/home",
];
EOF
    cat > src/notes.txt <<'EOF'
v1
EOF
    cat > package.json <<'EOF'
{
  "name": "fixture-c",
  "scripts": { "test": "node test.js" }
}
EOF
    cat > test.js <<'EOF'
const fs = require("fs");
const src = fs.readFileSync("src/routes.ts", "utf8");
if (/[<>=]{7}/.test(src)) { console.error("FAIL: conflict markers present"); process.exit(1); }
const missing = ["/home", "/about", "/contact"].filter((r) => !src.includes(r));
if (missing.length) { console.error("FAIL: missing routes: " + missing.join(", ")); process.exit(1); }
console.log("ok: home, about, contact all present");
EOF
    commit "base: routes + notes + test"
    $GIT push -q origin main

    $GIT checkout -q -b develop
    cat > src/routes.ts <<'EOF'
export const routes = [
  "/home",
  "/about",
];
EOF
    commit "develop: add /about route"
    $GIT push -q origin develop

    $GIT checkout -q main
    $GIT checkout -q -b feature
    cat > src/routes.ts <<'EOF'
export const routes = [
  "/home",
  "/contact",
];
EOF
    commit "feature: add /contact route"

    # Dirty the working tree: modify a tracked file + add an untracked file, leave uncommitted.
    printf 'v2 WIP\n' > src/notes.txt
    printf 'scratch work\n' > scratch.txt
    ;;

  *)
    echo "unknown scenario: $SCENARIO" >&2
    exit 1
    ;;
esac

echo "fixture ready: $DEST/repo (branch: $($GIT rev-parse --abbrev-ref HEAD))"
